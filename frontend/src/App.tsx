function NavItem({ to, label, icon }: { to: string; label: string; icon: React.ReactNode }) {
  const location = useLocation();
  const active = location.pathname === to;
  return (
    <Link className={`nav-item ${active ? "active" : ""}`} to={to}>
      {icon}<span>{label}</span>
    </Link>
  );
}

