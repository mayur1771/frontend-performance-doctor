function Analyze() {
  const [url, setUrl] = useState("https://demo.example.com");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [analysis, setAnalysis] = useState<Analysis | null>(null);

  async function handleAnalyze(e: React.FormEvent) {
    e.preventDefault();
    setError("");
    setAnalysis(null);
    setLoading(true);
    try {
      const result = await createAnalysis(url.trim());
      setAnalysis(result);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Analysis failed");
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="page">
      <PageHeader
        eyebrow="New report"
        title="Analyze a website"
        description="Enter a URL to generate a deterministic demo performance report."
      />

      <section className="panel analyze-form">
        <div className="form-icon"><Search size={22} /></div>
        <div className="form-copy">
          <h3>Start a performance analysis</h3>
          <p>Demo mode creates consistent metrics from the URL. This keeps the project reliable during local demos and interviews.</p>
        </div>
        <form onSubmit={handleAnalyze}>
          <label htmlFor="url">Website URL</label>
          <div className="input-row">
            <input id="url" value={url} onChange={(e) => setUrl(e.target.value)} placeholder="https://example.com" />
            <button className="primary-btn" disabled={loading || !url.trim()}>
              {loading ? "Analyzing..." : "Analyze"}
            </button>
          </div>
        </form>
        {error && <div className="error-box">{error}</div>}
      </section>

      {loading && <LoadingCard />}
      {analysis && <AnalysisReport analysis={analysis} />}
    </div>
  );
}

