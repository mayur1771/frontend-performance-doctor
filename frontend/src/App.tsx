function SettingsPage() {
  const [notifications, setNotifications] = useState(false);
  async function enableNotifications() {
    if (!("Notification" in window)) return;
    const permission = await Notification.requestPermission();
    setNotifications(permission === "granted");
  }
  return (
    <div className="page">
      <PageHeader eyebrow="Preferences" title="Settings" description="Configure local demo preferences." />
      <section className="panel settings">
        <div className="setting-row">
          <div><strong>Browser notifications</strong><p>Allow critical demo recommendations to trigger a browser notification.</p></div>
          <button className="secondary-btn" onClick={enableNotifications}>{notifications ? "Enabled" : "Enable"}</button>
        </div>
        <div className="setting-row">
          <div><strong>Demo mode</strong><p>Demo mode is always enabled in this portfolio version so the application remains reliable without crawling external sites.</p></div>
          <span className="status-badge ok">Active</span>
        </div>
      </section>
    </div>
  );
}

function StatCard({ icon, label, value, meta }: { icon: React.ReactNode; label: string; value: string; meta: string }) {
  return <div className="stat-card"><div className="stat-icon">{icon}</div><span>{label}</span><strong>{value}</strong><small>{meta}</small></div>;
}

function ScoreBadge({ score }: { score: number }) {
  return <span className={`score-badge ${score >= 90 ? "good" : score >= 75 ? "warn" : "bad"}`}>{score}</span>;
}

function StatusRow({ label, status, ok }: { label: string; status: string; ok: boolean }) {
  return <div className="status-row"><div><span className={`status-dot ${ok ? "ok" : "bad"}`} />{label}</div><strong>{status}</strong></div>;
}

function Metric({ label, value, good }: { label: string; value: string; good: boolean }) {
  return <div className="metric"><span>{label}</span><strong>{value}</strong><small className={good ? "good-text" : "bad-text"}>{good ? "Good" : "Needs attention"}</small></div>;
}

function ScoreCard({ title, score }: { title: string; score: number }) {
  return <div className="mini-score"><div><span>{title}</span><strong>{score}</strong></div><div className="progress"><span style={{ width: `${score}%` }} /></div></div>;
}

function EmptyState({ title = "No reports yet", description = "Run your first analysis to populate this workspace." }: { title?: string; description?: string }) {
  return <div className="empty"><Gauge size={28} /><h3>{title}</h3><p>{description}</p><Link className="primary-btn" to="/analyze">Run analysis</Link></div>;
}

function LoadingCard() {
  return <section className="panel loading-card"><div className="spinner" /><h3>Running analysis engine...</h3><p>Calculating loading, network, asset and rendering signals.</p></section>;
}

function ArchitectureNode({ title, subtitle }: { title: string; subtitle: string }) {
  return <div className="architecture-node"><div className="node-icon"><Terminal size={20} /></div><div><strong>{title}</strong><span>{subtitle}</span></div></div>;
}

